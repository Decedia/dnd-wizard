"use client";

import { useEffect, useRef, useState } from "react";

const sections = [
  { id: "identity", label: "Identity", Icon: UserIcon },
  { id: "stats", label: "Stats", Icon: StatsIcon },
  { id: "skills", label: "Skills", Icon: SkillsIcon },
  { id: "features", label: "Features", Icon: FeaturesIcon },
  { id: "inventory", label: "Inventory", Icon: InventoryIcon },
  { id: "spells", label: "Spells", Icon: SpellsIcon },
  { id: "appearance", label: "Appearance", Icon: AppearanceIcon },
];

export function SectionNav() {
  const [active, setActive] = useState(sections[0].id);
  const observerRef = useRef<IntersectionObserver | null>(null);

  useEffect(() => {
    observerRef.current = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            setActive(entry.target.id);
          }
        });
      },
      { rootMargin: "-20% 0px -70% 0px", threshold: 0 }
    );

    sections.forEach(({ id }) => {
      const el = document.getElementById(id);
      if (el) observerRef.current?.observe(el);
    });

    return () => observerRef.current?.disconnect();
  }, []);

  const scrollTo = (id: string) => {
    const el = document.getElementById(id);
    el?.scrollIntoView({ behavior: "smooth", block: "start" });
  };

  return (
    <nav
      className="fixed right-2 top-1/2 z-40 hidden md:flex -translate-y-1/2 flex-col gap-3 rounded-full border border-parchment/10 bg-charcoal-light/90 p-2 shadow-xl backdrop-blur-xl"
      aria-label="Section navigation"
    >
      {sections.map(({ id, label, Icon }) => (
        <button
          key={id}
          onClick={() => scrollTo(id)}
          aria-label={label}
          title={label}
          className={`flex h-10 w-10 items-center justify-center rounded-full transition-colors ${
            active === id ? "text-gold" : "text-parchment/50 hover:text-parchment"
          }`}
        >
          <Icon className="h-5 w-5" />
        </button>
      ))}
    </nav>
  );
}

function UserIcon({ className }: { className?: string }) {
  return (
    <svg className={className} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round">
      <path d="M20 21v-2a4 4 0 00-4-4H8a4 4 0 00-4 4v2" />
      <circle cx="12" cy="7" r="4" />
    </svg>
  );
}

function StatsIcon({ className }: { className?: string }) {
  return (
    <svg className={className} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round">
      <path d="M18 20V10" />
      <path d="M12 20V4" />
      <path d="M6 20v-6" />
    </svg>
  );
}

